#!/usr/bin/env bash
# Pull workflow evidence about how a deck was built from coding-agent session logs.
# Read-only. Prints timestamps, counts and the user's own short messages; never tool output.
#
# Usage: session_evidence.sh <deck file name or path fragment> [call start in UTC, e.g. 2026-11-19T14:00]
# Log timestamps are UTC, so give the call start in UTC too.
# Only logs changed in the last DAYS days are searched (default 7): DAYS=14 session_evidence.sh deck.html
#
# Sources, each skipped quietly if absent:
#   Claude Code  ~/.claude/projects/**/*.jsonl          tested
#   Codex        ~/.codex/sessions/**/rollout-*.jsonl   UNTESTED: written from Codex's log format, never run on a real edit
#   Cursor       Cursor's state.vscdb (SQLite)          UNTESTED: written from Cursor's storage format, never run on a real chat
set -euo pipefail
deck="${1:?give the deck file name, e.g. renewals-deck.html}"
call="${2:-}"
days="${DAYS:-7}"
command -v jq >/dev/null || { echo "jq is needed (brew install jq)"; exit 1; }
found=0
NOISE='<(command-|local-command|task-notification|system-reminder|environment_context|user_instructions|permissions)|session is being continued|Base directory for this skill|# AGENTS.md|^\S+\s+\[Image'

count() { printf '%s\n' "$1" | grep -c . || true; }

# report <label> <edit times> <command times> <user messages as "time<TAB>text">
report() {
  local label="$1" edits="$2" runs="$3" msgs="$4" n r
  found=1
  echo "== $label"
  n=$(count "$edits"); r=$(count "$runs")
  echo "deck edits: $n"
  if [ "$n" -gt 0 ]; then
    echo "first edit: $(printf '%s\n' "$edits" | grep . | head -1)   last edit: $(printf '%s\n' "$edits" | grep . | tail -1)"
    [ -n "$call" ] && echo "  on call day before the call starts: $(printf '%s\n' "$edits" | awk -v c="$call" 'NF && $0 >= substr(c,1,10) && $0 < c' | wc -l | tr -d ' ')"
    echo "edits per day:"; printf '%s\n' "$edits" | grep . | cut -c1-10 | sort | uniq -c | sed 's/^/  /'
  fi
  # Decks generated by a build script show up as shell commands, not edits.
  echo "shell commands naming the deck (builds, copies, opens): $r"
  if [ "$r" -gt 0 ]; then
    echo "first: $(printf '%s\n' "$runs" | grep . | head -1)   last: $(printf '%s\n' "$runs" | grep . | tail -1)"
    [ -n "$call" ] && echo "  on call day before the call starts: $(printf '%s\n' "$runs" | awk -v c="$call" 'NF && $0 >= substr(c,1,10) && $0 < c' | wc -l | tr -d ' ')"
  fi
  echo "last 40 user messages before the call (first 160 chars; look for corrections, deadlines, 'one more'):"
  printf '%s\n' "$msgs" | grep . | grep -v -E "$NOISE" \
    | awk -F'\t' -v c="$call" 'c=="" || $1 < c' | tail -40 || true
}

# ---- Claude Code (tested) ----------------------------------------------------
croot="${CLAUDE_PROJECTS_DIR:-$HOME/.claude/projects}"
if [ -d "$croot" ]; then
  # Worktrees get their own project folders, so search all of them.
  for f in $(find "$croot" -name '*.jsonl' -not -path '*/subagents/*' -mtime -"$days" -print0 2>/dev/null \
             | xargs -0 grep -l -F "$deck" 2>/dev/null || true); do
    edits=$(jq -r --arg d "$deck" 'select(.type=="assistant") | .timestamp as $t | .message.content[]?
      | select(.type=="tool_use" and (.name|test("^(Edit|Write|MultiEdit|NotebookEdit)$")))
      | select((.input.file_path // .input.notebook_path // "")|contains($d)) | $t' "$f" | sort)
    runs=$(jq -r --arg d "$deck" 'select(.type=="assistant") | .timestamp as $t | .message.content[]?
      | select(.type=="tool_use" and .name=="Bash") | select((.input.command // "")|contains($d)) | $t' "$f" | sort)
    msgs=$(jq -r 'select(.type=="user") | .timestamp as $t
      | (.message.content | if type=="string" then . else (map(select(.type=="text") | .text) | join(" ")) end) as $m
      | select($m != "") | [$t, ($m | gsub("\\s+";" ") | .[0:160])] | @tsv' "$f")
    # Session id only: the project folder name can name a client.
    report "Claude Code session $(basename "$f" .jsonl)" "$edits" "$runs" "$msgs"
  done
fi

# ---- Codex (UNTESTED) ---------------------------------------------------------
xroot="${CODEX_SESSIONS_DIR:-$HOME/.codex/sessions}"
if [ -d "$xroot" ]; then
  for f in $(find "$xroot" -name '*.jsonl' -mtime -"$days" -print0 2>/dev/null \
             | xargs -0 grep -l -F "$deck" 2>/dev/null || true); do
    # A tool call is a response_item whose payload type ends in "call"; apply_patch is an edit.
    calls=$(jq -r --arg d "$deck" 'select(.type=="response_item" and ((.payload.type // "")|endswith("call")))
      | (.payload | tostring) as $p | select($p|contains($d))
      | [.timestamp, (if ($p|test("apply_patch|\\*\\*\\* (Update|Add) File")) then "edit" else "run" end)] | @tsv' "$f" | sort)
    edits=$(printf '%s\n' "$calls" | awk -F'\t' '$2=="edit"{print $1}')
    runs=$(printf '%s\n' "$calls" | awk -F'\t' '$2=="run"{print $1}')
    msgs=$(jq -r 'select(.type=="response_item" and .payload.type=="message" and .payload.role=="user") | .timestamp as $t
      | ([.payload.content[]? | .text // empty] | join(" ")) as $m | select($m != "")
      | [$t, ($m | gsub("\\s+";" ") | .[0:160])] | @tsv' "$f")
    report "Codex session $(basename "$f" .jsonl) (UNTESTED reader)" "$edits" "$runs" "$msgs"
  done
fi

# ---- Cursor (UNTESTED) --------------------------------------------------------
for db in "${CURSOR_STATE_DB:-}" "$HOME/Library/Application Support/Cursor/User/globalStorage/state.vscdb" \
          "$HOME/.config/Cursor/User/globalStorage/state.vscdb"; do
  [ -n "$db" ] && [ -f "$db" ] || continue
  command -v sqlite3 >/dev/null || { echo "Cursor found, but sqlite3 is needed to read it"; break; }
  # Each chat message is a JSON row keyed bubbleId:<chat>:<message>; type 1 is the person, 2 is the AI.
  rows=$(sqlite3 -readonly "$db" "SELECT value FROM cursorDiskKV WHERE key LIKE 'bubbleId:%' AND value LIKE '%' || replace('$deck','''','') || '%';" 2>/dev/null || true)
  [ -z "$rows" ] && continue
  ai=$(printf '%s\n' "$rows" | jq -r 'select(.type==2) | (.createdAt // .timingInfo.clientStartTime // "no-time") | tostring' 2>/dev/null | sort)
  msgs=$(printf '%s\n' "$rows" | jq -r 'select(.type==1) | [((.createdAt // "no-time")|tostring), ((.text // "") | gsub("\\s+";" ") | .[0:160])] | @tsv' 2>/dev/null)
  report "Cursor chat history (UNTESTED reader; AI replies naming the deck are counted as commands)" "" "$ai" "$msgs"
  break
done

[ "$found" -eq 0 ] && echo "No session log from the last $days days mentions $deck (searched Claude Code, Codex, Cursor)"
exit 0
